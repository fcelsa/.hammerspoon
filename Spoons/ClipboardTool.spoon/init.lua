local function _ageLabel(ts, now)
   if type(ts) ~= "number" then return nil end
   local delta = now - ts
   if delta < 0 then delta = 0 end
   if delta < 60 then
      return delta .. "s"
   elseif delta < 3600 then
      return math.floor(delta / 60) .. "m"
   elseif delta < 86400 then
      return math.floor(delta / 3600) .. "h"
   end
   return math.floor(delta / 86400) .. "d"
end

local function _utf8LengthOrBytes(s)
   local ok, len = pcall(utf8.len, s)
   if ok and len ~= nil then return len end
   return #s
end

local function _formatBytes(value)
   if type(value) ~= "number" then return nil end
   if value < 1024 then
      return value .. " byte"
   elseif value < 1024 * 1024 then
      return math.floor((value + 512) / 1024) .. "kb"
   end
   return string.format("%.1fmb", value / (1024 * 1024))
end

local function _estimateDataUrlBytes(data_url)
   if type(data_url) ~= "string" then return nil end
   local payload = data_url:match("^data:[^;]+;base64,(.+)$")
   if payload == nil then return #data_url end
   local padding = 0
   if payload:sub(-2) == "==" then
      padding = 2
   elseif payload:sub(-1) == "=" then
      padding = 1
   end
   return math.floor((#payload * 3) / 4) - padding
end

local function _firstTextFormat()
   local all_types = {}
   local ok_content, content_types = pcall(hs.pasteboard.contentTypes)
   if ok_content and type(content_types) == "table" then
      for _, t in ipairs(content_types) do table.insert(all_types, t:lower()) end
   end

   local ok_pb, pb_types = pcall(hs.pasteboard.pasteboardTypes)
   if ok_pb and type(pb_types) == "table" then
      for _, t in ipairs(pb_types) do table.insert(all_types, t:lower()) end
   end

   for _, t in ipairs(all_types) do
      if t:find("utf16", 1, true) ~= nil then return "utf-16" end
   end
   for _, t in ipairs(all_types) do
      if t:find("utf8", 1, true) ~= nil then return "utf-8" end
   end
   for _, t in ipairs(all_types) do
      if t:find("rtf", 1, true) ~= nil then return "rtf" end
   end
   for _, t in ipairs(all_types) do
      if t:find("html", 1, true) ~= nil then return "html" end
   end
   return nil
end

local function _lineBreakLabel(s)
   if type(s) ~= "string" then return nil end
   local has_crlf = s:find("\r\n", 1, true) ~= nil
   local has_lf = s:find("\n", 1, true) ~= nil
   local has_cr = s:find("\r", 1, true) ~= nil

   if has_crlf then return "newline CRLF" end
   if has_lf and has_cr then return "newline LF+CR" end
   if has_lf then return "newline LF" end
   if has_cr then return "newline CR" end
   return nil
end

local function _entrySubText(entry, now)
   local parts = {}
   local age = _ageLabel(entry.t, now)
   if age then table.insert(parts, "Age " .. age) end

   if entry.type == "image" then
      local image_bytes = entry.bytes or _estimateDataUrlBytes(entry.content)
      table.insert(parts, "image " .. (_formatBytes(image_bytes) or "n/a"))
   elseif entry.type == "text" then
      if type(entry.fmt) == "string" then
         local text_bytes = entry.bytes
         if type(text_bytes) ~= "number" and type(entry.content) == "string" then text_bytes = #entry.content end
         table.insert(parts, entry.fmt .. " " .. ((text_bytes and (text_bytes .. " byte")) or "n/a"))
      else
         local chars = entry.chars
         if type(chars) ~= "number" and type(entry.content) == "string" then chars = _utf8LengthOrBytes(entry.content) end
         table.insert(parts, "char " .. tostring(chars or 0))
      end

      local line_breaks = _lineBreakLabel(entry.content)
      if line_breaks then table.insert(parts, line_breaks) end
   end

   if #parts == 0 then return nil end
   return table.concat(parts, " — ")
end

local function _isDarkMode()
   return hs.host.interfaceStyle() == "Dark"
end

local function _imageFromNames(names)
   for _, name in ipairs(names) do
      if type(name) == "string" and name ~= "" then
         local ok, image = pcall(hs.image.imageFromName, name)
         if ok and image ~= nil then return image end
      end
   end
   return nil
end

function obj:_updateMenubarAppearance()
   if self.menubaritem == nil then return end

   if not self.use_system_menubar_icon then
      self.menubaritem:setIcon(nil)
      self.menubaritem:setTitle(self.menubar_title)
      return
   end

   local dark_mode = _isDarkMode()
   local primary = dark_mode and self.menubar_icon_dark or self.menubar_icon_light
   local secondary = dark_mode and self.menubar_icon_light or self.menubar_icon_dark
   local icon = _imageFromNames({
      primary,
      secondary,
      "clipboard",
      "clipboard.fill",
      "doc.on.clipboard",
      "doc.on.doc",
      "NSTouchBarComposeTemplate",
      "NSImageNameActionTemplate",
   })

   if icon ~= nil and self.menubaritem:setIcon(icon, true) ~= nil then
      self.menubaritem:setTitle(nil)
   else
      self.menubaritem:setIcon(nil)
      self.menubaritem:setTitle(self.menubar_title)
   end
end

