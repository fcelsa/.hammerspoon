function obj:clearLastItem()
   table.remove(clipboard_history, 1)
   _persistHistory()
   last_change = pasteboard.changeCount()
end

-- Internal method: deduplicate the given list, and restrict it to the history size limit
function obj:dedupe_and_resize(list)
   local res = {}
   local hashes = {}
   local now = os.time()
   local max_age_days = tonumber(self.prune_max_age_days) or 0
   local pruning_enabled = max_age_days > 0
   local cutoff = pruning_enabled and (now - (max_age_days * 86400)) or nil

   for i, v in ipairs(list) do
      if #res < self.hist_size then
         -- Backward-compatible normalization (older entries may miss fields).
         if type(v) == "string" then
            v = { type = "text", content = v }
            if pruning_enabled then v.t = now end
         end

         if type(v) == "table" and type(v.content) == "string" then
            if v.type == nil then v.type = "text" end
            if pruning_enabled and type(v.t) ~= "number" then v.t = now end

            if (not pruning_enabled) or (v.t >= cutoff) then
               local hash = hashfn(v.content)
               if (not self.deduplicate) or (not hashes[hash]) then
                  table.insert(res, v)
                  hashes[hash] = true
               end
            end
         end
      end
   end
   return res
end

--- ClipboardTool:pasteboardToClipboard(item)
--- Method
--- Add the given string to the history
---
--- Parameters:
---  * item - string to add to the clipboard history
---  * meta - optional table with lightweight metadata (e.g. `fmt`, `bytes`, `chars`)
---
--- Returns:
---  * None
function obj:pasteboardToClipboard(item_type, item, meta)
   local entry = { type = item_type, content = item }
   if type(meta) == "table" then
      for k, v in pairs(meta) do
         entry[k] = v
      end
   end
   if (tonumber(self.prune_max_age_days) or 0) > 0 then entry.t = os.time() end
   table.insert(clipboard_history, 1, entry)
   clipboard_history = self:dedupe_and_resize(clipboard_history)
   _persistHistory() -- updates the saved history
end

